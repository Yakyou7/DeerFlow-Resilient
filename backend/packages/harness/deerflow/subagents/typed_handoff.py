"""Typed Subagent Handoff Protocol (Route C / RFC-003).

Inspired by:
- ai-memory: Typed Handoff State Machine (crates/ai-memory-core/src/handoff.rs)
- ai-agent-book Chapter 10: Multi-Agent Collaboration
- Google Research harness2 (arXiv:2610.14224)

Provides structured outcome reporting (attempted_paths, fatal_blocks,
deliverables, remaining_goals) to eliminate duplicate work and minimize
parent deliberation tokens.
"""

from __future__ import annotations

import re
from typing import Any, Literal

from pydantic import BaseModel, Field

HandoffStatus = Literal["completed", "blocked", "partial", "failed"]


class TypedHandoff(BaseModel):
    """Structured handoff contract emitted upon subagent completion."""

    status: HandoffStatus = Field(
        default="completed",
        description="Execution status from the subagent perspective",
    )
    attempted_paths: list[str] = Field(
        default_factory=list,
        description="Actions or strategies attempted by the subagent and their outcomes",
    )
    fatal_blocks: list[str] = Field(
        default_factory=list,
        description="Insurmountable blockers encountered (informs lead agent not to retry blindly)",
    )
    deliverables: list[str] = Field(
        default_factory=list,
        description="Concrete file handles, URLs, IDs, or output paths generated by the subagent",
    )
    remaining_goals: list[str] = Field(
        default_factory=list,
        description="Unfinished tasks or recommended immediate next actions for the delegating agent",
    )
    summary: str = Field(
        default="",
        description="Concise summary of work performed (<= 250 characters)",
    )


def _clean_list_items(lines: list[str], max_items: int = 10) -> list[str]:
    cleaned: list[str] = []
    for line in lines:
        item = re.sub(r"^[-*•\d\.]+\s*", "", line).strip()
        if item and item.lower() not in ("none", "null", "n/a", "nil"):
            cleaned.append(item[:200])
        if len(cleaned) >= max_items:
            break
    return cleaned


def parse_typed_handoff(
    text: str | None,
    status: str = "completed",
    tool_receipts: list[dict[str, Any]] | None = None,
) -> TypedHandoff:
    """Parse or extract a TypedHandoff object from subagent result text and receipts."""
    raw = (text or "").strip()
    handoff_status: HandoffStatus = "completed"
    if status in ("failed", "timed_out", "polling_timed_out"):
        handoff_status = "failed"
    elif status == "cancelled":
        handoff_status = "blocked"

    # 1. Explicit <handoff> XML tag parsing (accepts closed or unclosed/truncated tags)
    tag_match = re.search(r"<handoff>(.*?)(?:</handoff>|\Z)", raw, re.DOTALL | re.IGNORECASE)
    if tag_match:
        body = tag_match.group(1).strip()
        sections: dict[str, list[str]] = {
            "status": [],
            "attempted": [],
            "fatal_blocks": [],
            "deliverables": [],
            "next": [],
            "summary": [],
        }
        current_section = "summary"
        for line in body.splitlines():
            line_str = line.strip()
            if not line_str:
                continue
            lower_line = line_str.lower()
            if lower_line.startswith("status:"):
                val = line_str.split(":", 1)[1].strip().lower()
                if val in ("completed", "blocked", "partial", "failed"):
                    handoff_status = val  # type: ignore[assignment]
                continue
            elif any(lower_line.startswith(p) for p in ("attempted:", "attempted_paths:", "attempted paths:")):
                current_section = "attempted"
                rest = line_str.split(":", 1)[1].strip()
                if rest:
                    sections[current_section].append(rest)
                continue
            elif any(lower_line.startswith(p) for p in ("fatal_blocks:", "fatal blocks:", "blockers:", "blocks:")):
                current_section = "fatal_blocks"
                rest = line_str.split(":", 1)[1].strip()
                if rest:
                    sections[current_section].append(rest)
                continue
            elif any(lower_line.startswith(p) for p in ("deliverables:", "outputs:", "artifacts:")):
                current_section = "deliverables"
                rest = line_str.split(":", 1)[1].strip()
                if rest:
                    sections[current_section].append(rest)
                continue
            elif any(lower_line.startswith(p) for p in ("next:", "remaining:", "remaining_goals:", "remaining goals:")):
                current_section = "next"
                rest = line_str.split(":", 1)[1].strip()
                if rest:
                    sections[current_section].append(rest)
                continue
            elif lower_line.startswith("summary:"):
                current_section = "summary"
                rest = line_str.split(":", 1)[1].strip()
                if rest:
                    sections[current_section].append(rest)
                continue

            sections[current_section].append(line_str)

        summary_text = " ".join(sections["summary"]).strip()[:250]
        if not summary_text:
            summary_text = raw[:150]

        return TypedHandoff(
            status=handoff_status,
            attempted_paths=_clean_list_items(sections["attempted"]),
            fatal_blocks=_clean_list_items(sections["fatal_blocks"]),
            deliverables=_clean_list_items(sections["deliverables"]),
            remaining_goals=_clean_list_items(sections["next"]),
            summary=summary_text,
        )

    # 2. Heuristic extraction fallback when explicit tag is absent
    deliverables: list[str] = []
    attempted_paths: list[str] = []
    fatal_blocks: list[str] = []
    remaining_goals: list[str] = []

    # Extract written files from tool receipts
    if tool_receipts:
        for r in tool_receipts:
            tname = r.get("tool_name") or r.get("name") or ""
            args = r.get("args") or {}
            if isinstance(args, dict):
                p = args.get("path") or args.get("file_path")
                if p and isinstance(p, str) and p not in deliverables:
                    deliverables.append(p)
            if tname and len(attempted_paths) < 6:
                attempted_paths.append(f"Executed tool: {tname}")

    # Regex search for files / deliverables in text
    file_matches = re.findall(
        r"(?:created|written|saved|output|deliverables?|artifacts?|file|wrote)\s*[:=]?\s*(?:to\s+)?[-*•\s]*['\"`]?([a-zA-Z0-9_\-\./\\]+\.[a-zA-Z0-9_]{1,10})['\"`]?",
        raw,
        re.IGNORECASE,
    )
    for fm in file_matches:
        if fm not in deliverables and not fm.endswith((".pyc", ".tmp")):
            deliverables.append(fm)

    # Search for blockers
    block_matches = re.findall(
        r"(?:blocked by|fatal error|cannot proceed|unresolvable blocker|failed due to)[:\s]+([^\n\r]+)",
        raw,
        re.IGNORECASE,
    )
    for bm in block_matches:
        fatal_blocks.append(bm.strip())

    if fatal_blocks and handoff_status == "completed":
        handoff_status = "blocked"

    # Derive concise summary
    first_paragraph = raw.split("\n\n")[0].replace("\n", " ").strip()
    summary = first_paragraph[:250] if first_paragraph else (f"Task {status}" if status else "No summary available")

    return TypedHandoff(
        status=handoff_status,
        attempted_paths=_clean_list_items(attempted_paths),
        fatal_blocks=_clean_list_items(fatal_blocks),
        deliverables=_clean_list_items(deliverables),
        remaining_goals=_clean_list_items(remaining_goals),
        summary=summary,
    )


def render_handoff_section(handoff: TypedHandoff) -> str:
    """Format the TypedHandoff into a compact, model-readable section."""
    lines = [
        f'<subagent_handoff status="{handoff.status}">',
        f"- **Summary**: {handoff.summary or 'Task execution concluded.'}",
    ]

    if handoff.deliverables:
        lines.append("- **Deliverables**:")
        for d in handoff.deliverables:
            lines.append(f"  - `{d}`")
    else:
        lines.append("- **Deliverables**: None")

    if handoff.fatal_blocks:
        lines.append("- **Fatal Blocks** (Do not repeat):")
        for fb in handoff.fatal_blocks:
            lines.append(f"  - ⚠️ {fb}")
    else:
        lines.append("- **Fatal Blocks**: None")

    if handoff.attempted_paths:
        lines.append("- **Attempted Paths**:")
        for ap in handoff.attempted_paths:
            lines.append(f"  - {ap}")

    if handoff.remaining_goals:
        lines.append("- **Recommended Next Actions**:")
        for rg in handoff.remaining_goals:
            lines.append(f"  - {rg}")

    lines.append("</subagent_handoff>")
    return "\n".join(lines)
